//! LLMQ parameters.

use dash_primitives::LlmqType;

/// Parameters of one LLMQ type.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct LlmqParams {
  /// LLMQ type these parameters belong to.
  pub llmq_type: LlmqType,
  /// Whether quorums rotate their members (DIP0024).
  pub use_rotation: bool,
  /// Number of members in a quorum.
  pub size: i32,
  /// Minimum number of valid members for a DKG to
  /// produce a commitment.
  pub min_size: i32,
  /// Number of signature shares needed to recover a
  /// signature.
  pub threshold: i32,
  /// Number of blocks between DKG sessions.
  pub dkg_interval: i32,
  /// Number of blocks in each DKG phase.
  pub dkg_phase_blocks: i32,
  /// Offset in the DKG interval of the first block
  /// that mines commitments.
  pub dkg_mining_window_start: i32,
  /// Offset in the DKG interval of the last block
  /// that mines commitments.
  pub dkg_mining_window_end: i32,
  /// Number of complaints that mark a member bad.
  pub dkg_bad_votes_threshold: i32,
  /// Number of quorums active for signing.
  pub signing_active_quorum_count: i32,
  /// Number of quorums whose connections are kept.
  pub keep_old_connections: i32,
  /// Number of quorums whose keys are kept.
  pub keep_old_keys: i32,
  /// Number of members sent all signature shares
  /// before giving up.
  pub recovery_members: i32,
}

